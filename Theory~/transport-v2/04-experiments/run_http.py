"""Per-request overhead model: HTTP headers (HTTP/1.1 text, HTTP/2 HPACK measured with the `hpack` library),
TLS 1.3 record overhead, TCP/IP headers, connection setup. Bodies are real encoder outputs from the base profile.
Run: python run_http.py > results/http.md

Measured here: header byte counts, HPACK sizes, body sizes. Taken from elsewhere: TLS full-handshake bytes
(results/tls.txt, measure_tls.sh), TLS record overhead 22 B (RFC 8446 5.2: 5 B header + 1 B inner type + 16 B AEAD tag),
TCP/IPv4 header 52 B per segment incl. timestamps option (RFC 791/9293/7323). Resumption/0-RTT sizes are ESTIMATES."""
import gzip
from functools import partial

import hpack
import zstandard as zstd

import wire
from gen import dataset

HOST = "analytics.mortris.example"
TOKEN = "x" * 43  # 32 random bytes base64url, as AnalyticsQueue.newIdentity
TLS_REC = 22
TCP_IP = 52
MSS = 1400


def h1_req(path, headers, body_len):
    lines = [f"POST {path} HTTP/1.1"] + [f"{k}: {v}" for k, v in headers] + [f"Content-Length: {body_len}", "", ""]
    return len("\r\n".join(lines))


V1_H = [("Host", HOST), ("Authorization", "Bearer " + TOKEN), ("Content-Type", "application/json"),
        ("Content-Encoding", "gzip"), ("Expect", "100-continue"), ("Connection", "keep-alive")]
V1_H_NOEXPECT = [h for h in V1_H if h[0] != "Expect"]
V2_H = [("Host", HOST), ("Authorization", "Bearer " + TOKEN)]
RESP_V1 = "HTTP/1.1 200 OK\r\nServer: nginx\r\nDate: Fri, 16 Oct 2026 19:03:07 GMT\r\nContent-Type: application/json\r\n" \
          "Content-Length: {}\r\nConnection: keep-alive\r\n\r\n"
RESP_V2 = "HTTP/1.1 200 OK\r\nDate: Fri, 16 Oct 2026 19:03:07 GMT\r\nContent-Length: {}\r\n\r\n"


def hpack_sizes(path, headers, n=3):
    enc = hpack.Encoder()
    out = []
    for i in range(n):
        hs = [(":method", "POST"), (":scheme", "https"), (":authority", HOST), (":path", path)]
        hs += [(k.lower(), v) for k, v in headers if k not in ("Host", "Connection", "Expect")]
        hs.append(("content-length", str(3000 + i * 17)))
        out.append(len(enc.encode(hs)))
    return out


def wire_bytes(app_up, app_down, records_up=1, records_down=1):
    """Add TLS record + TCP/IP overhead (no ACK piggyback modelling: +1 pure ACK each way)."""
    up = app_up + TLS_REC * records_up
    down = app_down + TLS_REC * records_down
    seg_up = -(-up // MSS) + 1
    seg_down = -(-down // MSS) + 1
    return up + seg_up * TCP_IP, down + seg_down * TCP_IP


def main():
    ds = dataset(1, installs=5)
    tr = dataset(2, installs=10)
    d = zstd.train_dictionary(16384, [wire.mtb2_encode(i, b) for i, bs in tr for b in bs], level=19)
    zc = zstd.ZstdCompressor(compression_params=zstd.ZstdCompressionParameters.from_level(
        19, format=zstd.FORMAT_ZSTD1_MAGICLESS, write_checksum=False, write_content_size=False, write_dict_id=False),
        dict_data=d)
    batches = [(i, b) for i, bs in ds for b in bs]
    n_ev = sum(len(b) for _, b in batches)
    mean_n = n_ev / len(batches)
    v1_body = sum(len(gzip.compress(wire.v1_json(i, b), 1)) for i, b in batches) / len(batches)
    v2_body = sum(2 + len(zc.compress(wire.mtb2_encode(i, b, with_install=False))) for i, b in batches) / len(batches)
    v1_resp = sum(len(wire.v1_response(b, b[-1]["ts"])) for _, b in batches) / len(batches)
    v2_resp = 10

    print("# HTTP/TLS/TCP overhead model (generated by run_http.py)\n")
    print(f"Batches: {len(batches)}, mean {mean_n:.1f} events. Mean body: V1 gzip-1 {v1_body:.0f} B, "
          f"MTB2 zstd-19+dict {v2_body:.0f} B (incl. 2 B frame prefix). Mean V1 response body {v1_resp:.0f} B "
          f"(not compressed today), MTB2 ack ~{v2_resp} B.\n")
    print("## Header bytes\n")
    print(f"- HTTP/1.1 V1 request headers (with Expect: 100-continue): {h1_req('/v1/events/batch', V1_H, 3000)} B")
    print(f"- HTTP/1.1 V1 request headers (without Expect): {h1_req('/v1/events/batch', V1_H_NOEXPECT, 3000)} B")
    print(f"- HTTP/1.1 V2 request headers (Host + Authorization + Content-Length only): {h1_req('/b', V2_H, 700)} B")
    print(f"- HTTP/1.1 response headers: V1-style {len(RESP_V1.format(3000))} B, minimal {len(RESP_V2.format(10))} B")
    print(f"- HTTP/2 HPACK request header block, requests 1..3 on one connection: V1 {hpack_sizes('/v1/events/batch', V1_H)}"
          f" B, V2 {hpack_sizes('/b', V2_H)} B (+9 B HEADERS frame + 9 B DATA frame each)")

    rows = []
    h1v1 = h1_req("/v1/events/batch", V1_H, 3000)
    h1v2 = h1_req("/b", V2_H, 700)
    hp1, hp2 = hpack_sizes("/v1/events/batch", V1_H), hpack_sizes("/b", V2_H)
    scen = [
        ("V1 today, warm HTTP/1.1 keep-alive", h1v1 + v1_body, len(RESP_V1.format(3000)) + v1_resp, 2, 1),
        ("V1 body + V1 headers, warm HTTP/2 (steady state)", hp1[2] + 18 + v1_body, 40 + v1_resp, 1, 1),
        ("MTB2, warm HTTP/1.1", h1v2 + v2_body, len(RESP_V2.format(10)) + v2_resp, 1, 1),
        ("MTB2, warm HTTP/2 (steady state)", hp2[2] + 18 + v2_body, 30 + v2_resp, 1, 1),
    ]
    print("\n## Per-request totals on the wire (app bytes + TLS records + TCP/IP), warm connection\n")
    print("| scenario | up B/req | down B/req | up B/event | down B/event | body share of up |\n|---|---:|---:|---:|---:|---:|")
    for name, up, down, ru, rd in scen:
        wu, wd = wire_bytes(up, down, ru, rd)
        body = v1_body if "V1" in name.split(",")[0] else v2_body
        rows.append((name, wu, wd))
        print(f"| {name} | {wu:.0f} | {wd:.0f} | {wu / mean_n:.1f} | {wd / mean_n:.1f} | {100 * body / wu:.0f}% |")

    print("\n## Connection setup (paid once per connection)\n")
    tcp = 3 * 64
    print(f"- TCP handshake ~{tcp} B (3 segments incl. options), +1 RTT")
    print("- TLS 1.3 full handshake, measured (results/tls.txt): client->server 302-319 B (X25519) or 1500-1728 B "
          "(X25519MLKEM768 hybrid, now default in OpenSSL 3.5+/Chrome); server->client 2817-5163 B (cert chain dominates)")
    print("- TLS 1.3 PSK resumption: no certificate chain; ESTIMATE 400-700 B up, 200-400 B down [estimate, not measured]")
    print("- TLS 1.3 0-RTT / QUIC 0-RTT: request rides in the first flight; replayable, so only for idempotent requests "
          "(RFC 8446 8, RFC 9001 9.2) [source]")
    for name, wu, wd in rows:
        if "MTB2, warm HTTP/1.1" in name:
            cold_up, cold_down = wu + tcp + 310, wd + 4000
            print(f"\nMTB2 single batch on a COLD connection (full TLS, classic X25519): ~{cold_up:.0f} B up / "
                  f"~{cold_down:.0f} B down vs warm {wu:.0f} / {wd:.0f}. Body is {100 * v2_body / (cold_up + cold_down):.0f}% "
                  f"of all bytes moved.")
    one_ev = len(zc.compress(wire.mtb2_encode(batches[0][0], batches[0][1][:1], with_install=False))) + 2
    one_v1 = len(gzip.compress(wire.v1_json(batches[0][0], batches[0][1][:1]), 1))
    print(f"\nSingle-event request: MTB2 body {one_ev} B vs V1 body {one_v1} B; HTTP/1.1 V2 headers alone {h1v2} B.")


if __name__ == "__main__":
    main()
