"""Size experiments: format x compressor matrix, ablation, attribution, batch-size curve.
Run: python run_size.py 10 base > results/sizes_base.md ; python run_size.py 10 rich > results/sizes_rich.md
(deterministic; ~4-8 min each on a laptop, brotli-11 dominates)
Test set: dataset(seed=1). Dictionaries are trained ONLY on dataset(seed=2) (different installs/UUIDs/hashes)."""
import gzip
import sys
import zlib
from functools import partial

import brotli
import zstandard as zstd

import wire
from gen import dataset

TEST_INSTALLS = int(sys.argv[1]) if len(sys.argv) > 1 else 10
RICH = len(sys.argv) > 2 and sys.argv[2] == "rich"


# ---------------------------------------------------------------- compressors
def c_none(b):
    return b


def c_gzip(level, b):
    return gzip.compress(b, level, mtime=0)


def c_deflate_raw(level, b):
    o = zlib.compressobj(level, zlib.DEFLATED, -15)
    return o.compress(b) + o.flush()


def c_brotli(q, b):
    return brotli.compress(b, quality=q)


def c_zstd(level, b, d=None, minimal=False):
    params = zstd.ZstdCompressionParameters.from_level(
        level, format=zstd.FORMAT_ZSTD1_MAGICLESS if minimal else zstd.FORMAT_ZSTD1,
        write_checksum=False, write_content_size=not minimal, write_dict_id=not minimal)
    return zstd.ZstdCompressor(compression_params=params, dict_data=d).compress(b)


def train(samples, size):
    return zstd.train_dictionary(size, samples, level=19)


# ---------------------------------------------------------------- data
TEST = dataset(1, installs=TEST_INSTALLS, rich=RICH)
TRAIN = dataset(2, installs=30, rich=RICH)
N_EVENTS = sum(len(b) for _, bs in TEST for b in bs)
N_BATCHES = sum(len(bs) for _, bs in TEST)


def payloads(enc, ds=TEST):
    return [enc(inst, b) for inst, bs in ds for b in bs]


def per_event(blobs, comp):
    return sum(len(comp(x)) for x in blobs) / N_EVENTS


def mtb2_cas(ds=TEST, **kw):
    """CAS simulation: server learns ctx/shape fingerprints from every delivered batch of that install."""
    out = []
    for inst, bs in ds:
        known = set()
        for b in bs:
            sec = {}
            out.append(wire.mtb2_encode(inst, b, known=set(known), sections=sec, **kw))
            known |= sec["fps"]
    return out


def main():
    print(f"# Size results (generated by run_size.py)\n\nTest set: {N_EVENTS} events, {N_BATCHES} batches "
          f"(mean {N_EVENTS / N_BATCHES:.1f} ev/batch), installs={TEST_INSTALLS}, profile={'rich' if RICH else 'base'}. Unit: bytes per event of the HTTP "
          f"body (sum of compressed bodies / events). Dictionaries trained on seed=2 only.\n")

    encoders = {
        "V1 JSON (exact current)": wire.v1_json,
        "V1 JSON all JSON-level opts": partial(wire.json_variant, dedupe=True, drop_event_id=True, hoist_device=True,
                                               hoist_session=True, time_delta=True, short_keys=True, hoist_game=True),
        "MessagePack rows (V1 structure)": wire.msgpack_rows,
        "CBOR rows (V1 structure)": wire.cbor_rows,
        "MessagePack compact rows": wire.msgpack_compact,
        "Protobuf generic Prop{k,v}": wire.pb_generic,
        "Protobuf typed (codegen)": wire.pb_typed,
        "MTB2 row-major": partial(wire.mtb2_encode, columnar=False),
        "MTB2 columnar": wire.mtb2_encode,
    }
    blobs = {k: payloads(f) for k, f in encoders.items()}
    blobs["MTB2 columnar + CAS ctx/shape cache"] = mtb2_cas()
    train_blobs = {k: payloads(f, TRAIN) for k, f in encoders.items()}
    train_blobs["MTB2 columnar + CAS ctx/shape cache"] = mtb2_cas(TRAIN)

    dicts = {k: train(v, 16384) for k, v in train_blobs.items()}
    comps = [
        ("none", lambda k: c_none),
        ("gzip-1", lambda k: partial(c_gzip, 1)),
        ("gzip-6", lambda k: partial(c_gzip, 6)),
        ("gzip-9", lambda k: partial(c_gzip, 9)),
        ("br-5", lambda k: partial(c_brotli, 5)),
        ("br-11", lambda k: partial(c_brotli, 11)),
        ("zstd-3", lambda k: partial(c_zstd, 3)),
        ("zstd-19", lambda k: partial(c_zstd, 19)),
        ("zstd-3+dict16K", lambda k: partial(c_zstd, 3, d=dicts[k])),
        ("zstd-19+dict16K", lambda k: partial(c_zstd, 19, d=dicts[k])),
        ("zstd-19+dict16K min-frame", lambda k: partial(c_zstd, 19, d=dicts[k], minimal=True)),
    ]
    print("## 1. Format x compressor matrix (B/event)\n")
    print("| format | " + " | ".join(c for c, _ in comps) + " |")
    print("|---|" + "---:|" * len(comps))
    table = {}
    for k, bl in blobs.items():
        row = []
        for cname, cf in comps:
            v = per_event(bl, cf(k))
            table[(k, cname)] = v
            row.append(f"{v:.1f}")
        print(f"| {k} | " + " | ".join(row) + " |")
        sys.stdout.flush()
    base = table[("V1 JSON (exact current)", "gzip-1")]
    print(f"\nBaseline = V1 JSON gzip-1 = {base:.1f} B/event (SDK uses CompressionLevel.Fastest).\n")
    print("Reduction vs baseline for selected cells:\n")
    for k, c in [("V1 JSON (exact current)", "gzip-6"), ("V1 JSON (exact current)", "br-11"),
                 ("V1 JSON (exact current)", "zstd-19+dict16K"), ("V1 JSON all JSON-level opts", "gzip-6"),
                 ("V1 JSON all JSON-level opts", "zstd-19+dict16K"), ("Protobuf typed (codegen)", "zstd-19+dict16K"),
                 ("MTB2 columnar", "gzip-6"), ("MTB2 columnar", "zstd-19+dict16K"),
                 ("MTB2 columnar + CAS ctx/shape cache", "zstd-19+dict16K min-frame")]:
        v = table[(k, c)]
        print(f"- {k} / {c}: {v:.1f} B/event, {100 * (1 - v / base):.1f}% smaller")

    # ------------------------------------------------------------ dictionary size sweep
    print("\n## 2. zstd dictionary size sweep (level 19)\n")
    print("| format | no dict | 2K | 4K | 8K | 16K | 32K | 64K |\n|---|---:|---:|---:|---:|---:|---:|---:|")
    for k in ("V1 JSON (exact current)", "MTB2 columnar"):
        row = [f"{per_event(blobs[k], partial(c_zstd, 19)):.1f}"]
        for sz in (2048, 4096, 8192, 16384, 32768, 65536):
            d = train(train_blobs[k], sz)
            row.append(f"{per_event(blobs[k], partial(c_zstd, 19, d=d)):.1f}")
        print(f"| {k} | " + " | ".join(row) + " |")

    # ------------------------------------------------------------ JSON ablation
    print("\n## 3. Ablation on V1 JSON: each optimization ALONE vs V1 (B/event)\n")
    opts = ["dedupe", "drop_event_id", "hoist_device", "hoist_session", "time_delta", "short_keys", "hoist_game"]
    jcomps = [("gzip-1", partial(c_gzip, 1)), ("gzip-6", partial(c_gzip, 6)), ("br-11", partial(c_brotli, 11)),
              ("zstd-19", partial(c_zstd, 19))]
    print("| change | raw | " + " | ".join(c for c, _ in jcomps) + " |\n|---|---:|" + "---:|" * len(jcomps))
    v1 = blobs["V1 JSON (exact current)"]
    ref = [per_event(v1, c_none)] + [per_event(v1, f) for _, f in jcomps]
    print("| V1 | " + " | ".join(f"{x:.1f}" for x in ref) + " |")
    for o in opts:
        bl = payloads(partial(wire.json_variant, **{o: True}))
        vals = [per_event(bl, c_none)] + [per_event(bl, f) for _, f in jcomps]
        print(f"| +{o} only | " + " | ".join(f"{x:.1f} ({x - r:+.1f})" for x, r in zip(vals, ref)) + " |")
    print("\n### Cumulative (in this order)\n")
    print("| step | raw | " + " | ".join(c for c, _ in jcomps) + " |\n|---|---:|" + "---:|" * len(jcomps))
    on = {}
    for o in opts:
        on[o] = True
        bl = payloads(partial(wire.json_variant, **on))
        vals = [per_event(bl, c_none)] + [per_event(bl, f) for _, f in jcomps]
        print(f"| +{o} | " + " | ".join(f"{x:.1f}" for x in vals) + " |")

    # ------------------------------------------------------------ MTB2 internal ablation
    print("\n## 4. MTB2 internal ablation (each feature switched OFF alone; B/event)\n")
    d16 = dicts["MTB2 columnar"]
    mcomps = [("raw", c_none), ("gzip-6", partial(c_gzip, 6)), ("zstd-19", partial(c_zstd, 19)),
              ("zstd-19+dict", partial(c_zstd, 19, d=d16))]
    print("| variant | " + " | ".join(c for c, _ in mcomps) + " |\n|---|" + "---:|" * len(mcomps))
    variants = {
        "MTB2 full (columnar, aliases, int-delta, install id)": blobs["MTB2 columnar"],
        "- columnar (row-major, same tokens)": blobs["MTB2 row-major"],
        "- aliases/ctxref (no automatic dup removal)": payloads(partial(wire.mtb2_encode, aliases=False)),
        "- int delta": payloads(partial(wire.mtb2_encode, int_delta=False)),
        "+ install id omitted (derived from auth)": payloads(partial(wire.mtb2_encode, with_install=False)),
        "+ CAS ctx/shape cache": blobs["MTB2 columnar + CAS ctx/shape cache"],
        "+ placed_state_hash omitted (server recomputes; game-specific)": payloads(
            lambda i, b: wire.mtb2_encode(i, [{**e, "properties": {k: v for k, v in e["properties"].items()
                                                                  if k != "placed_state_hash"}} for e in b])),
    }
    for k, bl in variants.items():
        print(f"| {k} | " + " | ".join(f"{per_event(bl, f):.1f}" for _, f in mcomps) + " |")

    # ------------------------------------------------------------ section attribution
    print("\n## 5. Where MTB2 bytes sit (uncompressed section sizes, B/event)\n")
    tot = {}
    for inst, bs in TEST:
        for b in bs:
            s = {}
            wire.mtb2_encode(inst, b, sections=s)
            for k, v in s.items():
                if k != "fps":
                    tot[k] = tot.get(k, 0) + v
    for k, v in tot.items():
        print(f"- {k}: {v / N_EVENTS:.2f}")

    # ------------------------------------------------------------ fixed batch size curve
    print("\n## 6. Batch-size curve: same events re-batched into fixed sizes (B/event)\n")
    flat = [(inst, e) for inst, bs in TEST for b in bs for e in b]
    sizes = (1, 5, 10, 25, 50, 100, 500)
    curve = [("V1 gzip-1", wire.v1_json, partial(c_gzip, 1)), ("V1 gzip-6", wire.v1_json, partial(c_gzip, 6)),
             ("V1 zstd-19+dict", wire.v1_json, partial(c_zstd, 19, d=dicts["V1 JSON (exact current)"])),
             ("MTB2 raw", wire.mtb2_encode, c_none), ("MTB2 gzip-6", wire.mtb2_encode, partial(c_gzip, 6)),
             ("MTB2 zstd-19", wire.mtb2_encode, partial(c_zstd, 19)),
             ("MTB2 zstd-19+dict", wire.mtb2_encode, partial(c_zstd, 19, d=d16))]
    print("| codec | " + " | ".join(f"n={s}" for s in sizes) + " |\n|---|" + "---:|" * len(sizes))
    for name, enc, comp in curve:
        row = []
        for s in sizes:
            tot_b = n = 0
            # group per install so a batch never mixes installs
            for inst, bs in TEST:
                ev = [e for b in bs for e in b]
                for i in range(0, len(ev), s):
                    chunk = ev[i:i + s]
                    tot_b += len(comp(enc(inst, chunk)))
                    n += len(chunk)
            row.append(f"{tot_b / n:.1f}")
        print(f"| {name} | " + " | ".join(row) + " |")
        sys.stdout.flush()

    # ------------------------------------------------------------ V1 leave-one-out attribution
    print("\n## 7. Where V1 bytes sit: leave-one-field-out on V1 JSON (B/event saved if field removed)\n")
    groups = {"event_id": ["event_id"], "session_id": ["session_id"], "occurred_at_client": ["occurred_at_client"],
              "session_elapsed_ms": ["session_elapsed_ms"], "device ctx (7 fields)": list(wire.DEVICE_KEYS),
              "sequence": ["sequence"], "name": ["name"]}
    prop_keys = sorted({k for _, bs in TEST for b in bs for e in b for k in e["properties"]})
    for k in prop_keys:
        groups["properties." + k] = [("p", k)]
    g1, g6 = per_event(v1, partial(c_gzip, 1)), per_event(v1, partial(c_gzip, 6))
    raw1 = per_event(v1, c_none)
    rows = []
    for gname, fields in groups.items():
        def enc(inst, b, fields=fields):
            evs = []
            for e in b:
                d = wire.v1_event(e)
                d["properties"] = dict(d["properties"])
                for f in fields:
                    if isinstance(f, tuple):
                        d["properties"].pop(f[1], None)
                    else:
                        d.pop(f, None)
                evs.append(d)
            return wire.jdump({"schema_version": 1, "project_id": wire.PROJECT_ID, "install_id": inst.install_id,
                               "sdk": {"name": "mortris-unity", "version": "0.2.0"},
                               "sent_at_client": wire.iso_ms(wire.sent_at(b)), "events": evs}).encode()
        bl = payloads(enc)
        rows.append((gname, raw1 - per_event(bl, c_none), g1 - per_event(bl, partial(c_gzip, 1)),
                     g6 - per_event(bl, partial(c_gzip, 6))))
    rows.sort(key=lambda r: -r[2])
    print(f"V1 totals: raw {raw1:.1f}, gzip-1 {g1:.1f}, gzip-6 {g6:.1f}\n")
    print("| field | raw saved | gzip-1 saved | gzip-6 saved |\n|---|---:|---:|---:|")
    for r in rows:
        print(f"| {r[0]} | {r[1]:.1f} | {r[2]:.1f} | {r[3]:.1f} |")

    # ------------------------------------------------------------ responses
    print("\n## 8. Server response size per batch (B/event)\n")
    resp = [wire.v1_response(b, b[-1]["ts"] + 400) for _, bs in TEST for b in bs]
    print(f"- V1 JSON response, raw: {per_event(resp, c_none):.1f}; gzip-6: {per_event(resp, partial(c_gzip, 6)):.1f}")
    print(f"- MTB2 ack (spec 7.2: 1 B status + varint first_seq + varint count + varint server_time_delta + "
          f"policy_epoch) ~ 8-12 B per batch = {10 * N_BATCHES / N_EVENTS:.2f} B/event (computed, not encoded here)")


if __name__ == "__main__":
    main()
