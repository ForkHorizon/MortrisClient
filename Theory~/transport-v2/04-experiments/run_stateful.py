"""Does cross-batch state pay off? Compares, per install and in upload order:
  A  stateless: trained 16K dictionary only
  B  stateful : trained dictionary + last ACKNOWLEDGED batch payload as extra raw-content prefix
               (server must keep that payload per install; resync = drop the reference)
  C  CAS caches only (content-addressed ctx/shape refs, spec 5.6) + trained dictionary
  D  B + C
Also: the cost of a lost reference (B when the reference is unknown -> client resends in A form: 1 extra RTT).
Run: python run_stateful.py [base|rich] > results/stateful_<profile>.md"""
import sys

import zstandard as zstd

import wire
from gen import dataset

RICH = len(sys.argv) > 1 and sys.argv[1] == "rich"


def comp(level, d):
    p = zstd.ZstdCompressionParameters.from_level(level, format=zstd.FORMAT_ZSTD1_MAGICLESS, write_checksum=False,
                                                   write_content_size=False, write_dict_id=False)
    return zstd.ZstdCompressor(compression_params=p, dict_data=d)


def main():
    test = dataset(1, installs=10, rich=RICH)
    train = dataset(2, installs=30, rich=RICH)
    trained = zstd.train_dictionary(16384, [wire.mtb2_encode(i, b) for i, bs in train for b in bs], level=19)
    tbytes = trained.as_bytes()
    za = comp(19, trained)
    tot = {"A": 0, "B": 0, "C": 0, "D": 0}
    n = 0
    for inst, bs in test:
        prev, known = None, set()
        for b in bs:
            n += len(b)
            plain = wire.mtb2_encode(inst, b, with_install=False)
            sec = {}
            cas = wire.mtb2_encode(inst, b, with_install=False, known=set(known), sections=sec)
            tot["A"] += len(za.compress(plain))
            tot["C"] += len(za.compress(cas))
            if prev is None:
                tot["B"] += len(za.compress(plain))
                tot["D"] += len(za.compress(cas))
            else:
                # raw-content dictionary: trained dictionary content followed by the previous acked payload
                # (zstd matches recent bytes most cheaply, so the previous batch goes last)
                rd = zstd.ZstdCompressionDict(tbytes + prev[0], dict_type=zstd.DICT_TYPE_RAWCONTENT)
                tot["B"] += len(comp(19, rd).compress(plain)) + 3  # +3 B: varint ref to acked batch
                rd2 = zstd.ZstdCompressionDict(tbytes + prev[1], dict_type=zstd.DICT_TYPE_RAWCONTENT)
                tot["D"] += len(comp(19, rd2).compress(cas)) + 3
            prev = (plain, cas)
            known |= sec["fps"]
    print(f"# Stateful vs stateless (generated by run_stateful.py), profile={'rich' if RICH else 'base'}\n")
    print(f"{n} events. MTB2 without install id, zstd-19, minimal frame. B/event:\n")
    names = {"A": "A stateless (trained dict)", "B": "B + previous acked batch as reference",
             "C": "C CAS ctx/shape cache", "D": "D = B + C"}
    for k, v in tot.items():
        print(f"- {names[k]}: {v / n:.2f} ({100 * (v / tot['A'] - 1):+.1f}% vs A)")


if __name__ == "__main__":
    main()
