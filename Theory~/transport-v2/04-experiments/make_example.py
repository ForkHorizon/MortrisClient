"""End-to-end example for 01-protocol-spec.md section 9: one ~20-event batch, V1 JSON -> MTB2 payload -> frame.
Writes results/example_batch_v1.json, results/example_payload.bin, results/example_frame.bin, results/example.md.
Run: python make_example.py"""
import gzip

import zstandard as zstd

import wire
from gen import dataset


def hexdump(b, start=0, width=16):
    out = []
    for i in range(0, len(b), width):
        chunk = b[i:i + width]
        out.append(f"{start + i:04x}  {chunk.hex(' '):<{width * 3}} {''.join(chr(c) if 32 <= c < 127 else '.' for c in chunk)}")
    return "\n".join(out)


def main():
    ds = dataset(1, installs=5)
    inst, batch = next((i, b) for i, bs in ds for b in bs if 18 <= len(b) <= 22 and any(e["name"] == "attempt_started" for e in b))
    v1 = wire.v1_json(inst, batch)
    sec = {}
    payload = wire.mtb2_encode(inst, batch, sections=sec)
    payload_noinst = wire.mtb2_encode(inst, batch, with_install=False)
    tr = dataset(2, installs=30)
    d = zstd.train_dictionary(16384, [wire.mtb2_encode(i, b) for i, bs in tr for b in bs], level=19)
    p = zstd.ZstdCompressionParameters.from_level(19, format=zstd.FORMAT_ZSTD1_MAGICLESS, write_checksum=False,
                                                   write_content_size=False, write_dict_id=False)
    z_dict = zstd.ZstdCompressor(compression_params=p, dict_data=d).compress(payload)
    z_nodict = zstd.ZstdCompressor(level=19).compress(payload)
    # frame prefix (spec 4): byte0 = version<<4 | codec (0x23 = v2, zstd); then uvarint dictionary registry id (1)
    frame = bytes([0x23, 0x01]) + z_dict
    _, dec = wire.mtb2_decode(payload)
    assert len(dec) == len(batch)
    open("results/example_batch_v1.json", "wb").write(v1)
    open("results/example_payload.bin", "wb").write(payload)
    open("results/example_frame.bin", "wb").write(frame)
    open("results/example_dict.bin", "wb").write(d.as_bytes())
    n = len(batch)
    with open("results/example.md", "w") as f:
        w = lambda s="": f.write(s + "\n")
        w("# Example batch (generated by make_example.py)\n")
        w(f"{n} events: " + ", ".join(e["name"] for e in batch) + "\n")
        w("| stage | bytes | B/event |\n|---|---:|---:|")
        for name, size in [("V1 JSON raw", len(v1)), ("V1 JSON gzip-1 (today)", len(gzip.compress(v1, 1))),
                           ("V1 JSON gzip-6", len(gzip.compress(v1, 6))), ("MTB2 payload raw", len(payload)),
                           ("MTB2 payload raw, install id omitted", len(payload_noinst)),
                           ("MTB2 zstd-19, no dictionary (standard frame)", len(z_nodict)),
                           ("MTB2 zstd-19 + 16K dictionary, minimal frame", len(z_dict)),
                           ("MTB2 frame on the wire (2 B prefix + compressed)", len(frame))]:
            w(f"| {name} | {size} | {size / n:.1f} |")
        w("\nMTB2 payload sections (bytes): " + ", ".join(f"{k}={v}" for k, v in sec.items() if k != "fps"))
        w("\n## V1 JSON, first event\n\n```json\n" + wire.jdump(wire.v1_event(batch[0])) + "\n```\n")
        off = 0
        w("## MTB2 payload hexdump by section\n")
        for k in ("header", "tables", "contexts", "shapes", "coldir", "body"):
            w(f"### {k} ({sec[k]} B)\n\n```\n{hexdump(payload[off:off + sec[k]], off)}\n```\n")
            off += sec[k]
        w(f"## Frame on the wire ({len(frame)} B)\n\n```\n{hexdump(frame)}\n```")
    print(open("results/example.md").read()[:3000])


if __name__ == "__main__":
    main()
