"""CPU cost of compressors on real batch payloads (base profile). Desktop numbers only: a mid-range Android core is
roughly 3-10x slower (ESTIMATE, not measured; see 07-open-questions.md). Python encoder timing is NOT representative
of C#; only the C-library compressor timings are meaningful.
Run: python run_cpu.py > results/cpu.md"""
import gzip
import platform
import statistics
import time
from functools import partial

import brotli
import zstandard as zstd

import wire
from gen import dataset


def bench(fn, blobs, reps=5):
    best = []
    for x in blobs:
        ts = []
        for _ in range(reps):
            t = time.perf_counter_ns()
            fn(x)
            ts.append(time.perf_counter_ns() - t)
        best.append(min(ts))
    return statistics.median(best) / 1000


def main():
    ds = dataset(1, installs=3)
    tr = dataset(2, installs=10)
    batches = [(i, b) for i, bs in ds for b in bs]
    print(f"# CPU (generated by run_cpu.py)\n\n{platform.platform()} / {platform.processor()} / python "
          f"{platform.python_version()}; zstd {zstd.ZSTD_VERSION}; {len(batches)} batches, median of per-batch best-of-5.\n")
    for fmt, enc in (("V1 JSON", wire.v1_json), ("MTB2", wire.mtb2_encode)):
        blobs = [enc(i, b) for i, b in batches]
        d = zstd.train_dictionary(16384, [enc(i, b) for i, bs in tr for b in bs], level=19)
        dd = zstd.ZstdCompressionDict(d.as_bytes())
        dd.precompute_compress(level=19)
        comps = {
            "gzip-1": partial(gzip.compress, compresslevel=1, mtime=0),
            "gzip-6": partial(gzip.compress, compresslevel=6, mtime=0),
            "br-5": partial(brotli.compress, quality=5),
            "br-11": partial(brotli.compress, quality=11),
            "zstd-3": zstd.ZstdCompressor(level=3).compress,
            "zstd-19": zstd.ZstdCompressor(level=19).compress,
            "zstd-3+dict": zstd.ZstdCompressor(level=3, dict_data=d).compress,
            "zstd-19+dict": zstd.ZstdCompressor(level=19, dict_data=d).compress,
            "zstd-19+dict (precomputed)": zstd.ZstdCompressor(level=19, dict_data=dd).compress,
        }
        print(f"## {fmt} (mean raw {sum(map(len, blobs)) / len(blobs):.0f} B/batch)\n")
        print("| codec | compress us/batch | decompress us/batch | out B/batch |\n|---|---:|---:|---:|")
        for name, c in comps.items():
            outs = [c(x) for x in blobs]
            if name.startswith("gzip"):
                dec = gzip.decompress
            elif name.startswith("br"):
                dec = brotli.decompress
            elif "dict" in name:
                dec = zstd.ZstdDecompressor(dict_data=d).decompress
            else:
                dec = zstd.ZstdDecompressor().decompress
            print(f"| {name} | {bench(c, blobs):.0f} | {bench(dec, outs):.0f} | {sum(map(len, outs)) / len(outs):.0f} |")
        print()
    t = bench(lambda ib: wire.mtb2_encode(*ib), batches, reps=3)
    print(f"MTB2 encode in pure Python: {t:.0f} us/batch (upper bound; C# would be far faster, not measured).")


if __name__ == "__main__":
    main()
