"""Conservative path (stay on JSON, minimal server change), measured step by step on both profiles.
Run: python run_conservative.py > results/conservative.md"""
import gzip
from functools import partial

import brotli
import zstandard as zstd

import wire
from gen import dataset


def main():
    print("# Conservative JSON path (generated by run_conservative.py)\n\nB/event of request body; "
          "dictionaries trained on seed=2.\n")
    steps = [
        ("1. V1 today (gzip-1)", wire.v1_json, "gzip1"),
        ("2. gzip-6 instead of Fastest", wire.v1_json, "gzip6"),
        ("3. + drop event_id (dedup by install_id+sequence)", partial(wire.json_variant, drop_event_id=True), "gzip6"),
        ("4. + device ctx table + time deltas", partial(wire.json_variant, drop_event_id=True, hoist_device=True,
                                                       time_delta=True), "gzip6"),
        ("5. step 4 + Brotli-11", partial(wire.json_variant, drop_event_id=True, hoist_device=True, time_delta=True),
         "br11"),
        ("6. step 4 + zstd-19 + 16K dict", partial(wire.json_variant, drop_event_id=True, hoist_device=True,
                                                   time_delta=True), "zdict"),
    ]
    print("| step | base | base vs today | rich | rich vs today |\n|---|---:|---:|---:|---:|")
    res = {}
    for prof in (False, True):
        test, train = dataset(1, installs=10, rich=prof), dataset(2, installs=30, rich=prof)
        n = sum(len(b) for _, bs in test for b in bs)
        for name, enc, comp in steps:
            blobs = [enc(i, b) for i, bs in test for b in bs]
            if comp == "gzip1":
                c = partial(gzip.compress, compresslevel=1, mtime=0)
            elif comp == "gzip6":
                c = partial(gzip.compress, compresslevel=6, mtime=0)
            elif comp == "br11":
                c = partial(brotli.compress, quality=11)
            else:
                d = zstd.train_dictionary(16384, [enc(i, b) for i, bs in train for b in bs], level=19)
                c = zstd.ZstdCompressor(level=19, dict_data=d).compress
            res[(name, prof)] = sum(len(c(x)) for x in blobs) / n
    for name, _, _ in steps:
        b, r = res[(name, False)], res[(name, True)]
        b0, r0 = res[(steps[0][0], False)], res[(steps[0][0], True)]
        print(f"| {name} | {b:.1f} | {100 * (b / b0 - 1):+.0f}% | {r:.1f} | {100 * (r / r0 - 1):+.0f}% |")


if __name__ == "__main__":
    main()
